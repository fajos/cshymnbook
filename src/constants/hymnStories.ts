/**
 * Retrieves the historical and spiritual origin story for a given hymn ID.
 * Returns null if no curated story is recorded for that hymn.
 */
export function getHymnStory(hymnId: number): HymnStory | null {
  return HYMN_STORIES[hymnId] || null;
}

/**
 * Returns all curated hymn stories as an array sorted by hymn number.
 */
export function getAllHymnStories(): HymnStory[] {
  return Object.values(HYMN_STORIES).sort((a, b) => a.hymnId - b.hymnId);
}

/**
 * Filters hymn stories by category ('all', 'cs_heritage', or 'general_classic').
 */
export function getHymnStoriesByCategory(
  category: 'all' | 'cs_heritage' | 'general_classic' = 'all'
): HymnStory[] {
  const all = getAllHymnStories();
  if (category === 'all') return all;
  return all.filter((s) => s.category === category);
}

/**
 * Searches hymn stories by title, author, hymn number, or narrative keywords.
 */
export function searchHymnStories(query: string): HymnStory[] {
  const q = query.trim().toLowerCase();
  if (!q) return getAllHymnStories();

  return getAllHymnStories().filter((s) => {
    return (
      (s.hymnNumber && s.hymnNumber.toLowerCase().includes(q)) ||
      s.title.toLowerCase().includes(q) ||
      s.author.toLowerCase().includes(q) ||
      (s.year && s.year.toLowerCase().includes(q)) ||
      (s.originStory && s.originStory.toLowerCase().includes(q)) ||
      (s.spiritualTakeaway && s.spiritualTakeaway.toLowerCase().includes(q))
    );
  });
}
